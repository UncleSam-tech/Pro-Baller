export function getClubById(id: string): Club {
  const found = CLUBS_DATABASE.find(c => c.id === id);
  return found || CLUBS_DATABASE[0];
}

export function getLeagueClubs(league: string): Club[] {
  return CLUBS_DATABASE.filter(c => c.league === league);
}

/**
 * Strictly filters valid league division opponents based on the player's club league ID.
 * Guarantees that only clubs from the EXACT same league division are returned.
 */
export function getValidLeagueOpponents(currentClub: Club | string): Club[] {
  const club = typeof currentClub === 'string' ? getClubById(currentClub) : currentClub;
  const sameDivisionOpponents = CLUBS_DATABASE.filter(c => c.league === club.league && c.id !== club.id);
  
  if (sameDivisionOpponents.length > 0) {
    return sameDivisionOpponents;
  }

  // Strict fallback to clubs in the exact same tier/division
  const sameTierOpponents = CLUBS_DATABASE.filter(c => c.tier === club.tier && c.id !== club.id);
  if (sameTierOpponents.length > 0) {
    return sameTierOpponents;
  }

  return CLUBS_DATABASE.filter(c => c.id !== club.id);
}

/**
 * Alias for getValidLeagueOpponents ensuring strict league division filtering everywhere
 */
export function getOpponentsForClub(club: Club): Club[] {
  return getValidLeagueOpponents(club);
}
